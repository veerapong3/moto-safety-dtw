import { z } from "zod";

export const loginSchema = z.object({
  username: z.string().min(1, "กรุณากรอกชื่อผู้ใช้"),
  password: z.string().min(1, "กรุณากรอกรหัสผ่าน"),
});

export const registrationSchema = z.object({
  prefix: z.enum(["เด็กชาย", "เด็กหญิง", "นาย", "นางสาว"]),
  firstName: z.string().min(1, "กรุณากรอกชื่อ"),
  lastName: z.string().min(1, "กรุณากรอกนามสกุล"),
  studentId: z.string().regex(/^[0-9]+$/, "เลขประจำตัวต้องเป็นตัวเลข"),
  grade: z.string().min(1),
  room: z.string().min(1),
  phoneNumber: z
    .string()
    .regex(/^[0-9]{9,10}$/, "เบอร์โทรต้องเป็นตัวเลข 9-10 หลัก"),
  brand: z.string().min(1),
  color: z.string().min(1),
  plateNumber: z
    .string()
    .regex(/^[ก-ฮ]{2,3}[0-9]+$/, "รูปแบบทะเบียนไม่ถูกต้อง เช่น ยนร456"),
  province: z.string().min(1),
  helmet: z.enum(["มี", "ไม่มี"]),
  pillionName: z.string().optional().default(""),
  bikeFileId: z.string().optional(),
  plateFileId: z.string().optional(),
  riderFileId: z.string().optional(),
});

export const settingsUpdateSchema = z.object({
  REGISTRATION_OPEN: z.string().optional(),
  CLOSED_MESSAGE: z.string().optional(),
  GRADES: z.string().optional(),
  ROOMS: z.string().optional(),
  BRANDS: z.string().optional(),
  COLORS: z.string().optional(),
  SAMPLE_BIKE_FILE_ID: z.string().optional(),
  SAMPLE_PLATE_FILE_ID: z.string().optional(),
  SAMPLE_RIDER_FILE_ID: z.string().optional(),
  SCHOOL_NAME: z.string().optional(),
  APP_TITLE: z.string().optional(),
  CONTACT_EMAIL: z.string().optional(),
  CURRENT_ACADEMIC_YEAR: z.string().optional(),
  CURRENT_SEMESTER: z.string().optional(),
  DRIVE_ROOT_FOLDER_ID: z.string().optional(),
});

